#!/usr/bin/env python3
"""合并多个上游规则源 -> 去重 -> 清洗 -> 输出 AdGuard Home 拦截规则

设计目标：稳定优先、长期免维护、支持大量规则源、支持超大输出（50M+）。
- 仅使用 Python 标准库，无第三方依赖
- 单个源失败自动跳过并重试，不中断整体任务
- 单文件优先：默认汇总为一个 adguard-filter.txt；仅当文件超过 GitHub
  100MB 硬限制的安全线（90MB）时才应急分片，保证推送永不失败

清洗与去重策略：
- 白名单剔除：@@ 开头的例外规则、#@# 元素白名单全部丢弃
- 装饰规则剔除：## #?# #$# 等浏览器端元素隐藏/CSS 注入规则（AdGuard Home 不支持）
- hosts 转换：0.0.0.0/127.0.0.1/::1 条目（含行尾注释、多余空格）-> ||domain^
- 通配格式转换：*.example.com 补全为 ||*.example.com^（保持通配语义），
  ||*.example.com 等带 || 的通配规则原样保留
- 规则形态收敛：仅保留 ||domain^ 与通配形态；||... 里 $ 及其后的修饰符一律丢弃；
  带路径的 |http/||domain/path 规则与 /正则/ 规则丢弃；通配格式的域名不做修改
  （*. 子域通配补全 || 锚定、||*.example.com 原样保留）；统一小写
- 域名严格校验：标签不允许 - 开头/结尾、不含下划线，排除脏数据
- 去重：大小写不敏感完全去重；父域与子域规则均原样保留，不做父子域剔除
"""
import glob
import math
import os
import re
from concurrent.futures import ThreadPoolExecutor
import sys
import time
import urllib.request
from datetime import datetime, timezone

SOURCES_FILE = "sources.txt"
OUTPUT_SINGLE = "adguard-filter.txt"        # 默认单文件汇总输出
OUTPUT_PART_FMT = "adguard-filter-{}.txt"   # 超限时应急分片输出（从 1 开始编号）
SIZE_LIMIT_MB = 90                           # 单文件安全上限（GitHub 硬限制 100MB）
PART_TARGET_MB = 45                          # 应急分片时每片目标大小
MIN_RULES = 100_000                          # 结果少于此行数视为异常，终止且不覆盖线上版本

COMMENT_PREFIXES = ("!", "#", "[")
COSMETIC_TOKENS = ("##", "#@#", "#?#", "#$#", "#@%#")
LOCAL_NAMES = {"localhost", "local", "broadcasthost", "localhost.localdomain"}
HOSTS_RE = re.compile(r"^(?:0\.0\.0\.0|127\.0\.0\.1|::1)\s+([^\s#]+)")
# 域名严格校验：标签不允许 - 开头/结尾、不含下划线，排除脏数据
DOMAIN_RE = re.compile(
    r"^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}$",
    re.IGNORECASE,
)

def fetch(url, retries=2):
    for attempt in range(retries + 1):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
            with urllib.request.urlopen(req, timeout=120) as r:
                return r.read().decode("utf-8", errors="ignore")
        except Exception as e:
            print(f"  [warn] 第 {attempt + 1} 次拉取失败: {e}", file=sys.stderr)
            if attempt < retries:
                time.sleep(5)
    return None  # 单个源失败不中断整体任务

def fetch_all(urls, workers=5):
    """5 路并发拉取全部源，返回 {url: text or None}，保持输入顺序。

    串行最坏耗时：20 源 × (3 次尝试 × 120s + 2 次间隔 × 5s) ≈ 123 分钟，会撞上
    工作流 90 分钟超时；5 路并发后最坏 ≈ ceil(20/5) × 370s ≈ 25 分钟，余量充足。"""
    results = {}
    with ThreadPoolExecutor(max_workers=workers) as ex:
        for url, text in zip(urls, ex.map(fetch, urls)):
            results[url] = text
    return results

def domain_rule(d):
    """域名清洗后转为 ||domain^，非法则返回 None"""
    d = d.lstrip("*.").rstrip(".").lower()
    if not d or d in LOCAL_NAMES:
        return None
    if DOMAIN_RE.match(d):
        return f"||{d}^"
    return None

def block_rule(line):
    """|| 开头的规则：丢弃 $ 修饰符；通配格式原样保留；纯域名收敛为 ||域名^；无法收敛则丢弃"""
    pattern = line.split("$", 1)[0].strip().lower()
    body = pattern[2:]
    if "/" in body:            # 带路径的 URL 规则，AdGuard Home 按主机名匹配用不到
        return None
    if "*" in body:            # 通配格式的域名：不做修改，原样保留（仅统一小写）
        return pattern
    if body.endswith("^"):
        body = body[:-1]
    body = body.rstrip("|")    # ||域名| 这类尾锚点写法
    return domain_rule(body)   # 复用域名校验：补 ^，丢弃非法域名与本机域名

def normalize(line):
    line = line.strip()
    # 空行、注释行（! # [Adblock Plus] 等来源标记）
    if not line or line.startswith(COMMENT_PREFIXES):
        return None
    # 白名单/例外规则：只保留阻止规则
    if line.startswith("@@"):
        return None
    # 浏览器端装饰规则（元素隐藏、CSS 注入），AdGuard Home 不支持
    if any(tok in line for tok in COSMETIC_TOKENS):
        return None
    # hosts 格式：0.0.0.0 domain [# comment]
    m = HOSTS_RE.match(line)
    if m:
        return domain_rule(m.group(1))
    # IP 前缀但无空白（如 0.0.0.0example.com）：malformed hosts 脏数据，丢弃
    if line.startswith(("0.0.0.0", "127.0.0.1", "::1")):
        return None
    # 标准拦截类 adblock 规则：统一收敛成 ||domain^
    if line.startswith("||"):
        return block_rule(line)
    # URL/路径类规则与正则规则：不是 ||domain^，丢弃
    if line.startswith("|http") or (line.startswith("/") and line.endswith("/")):
        return None
    # 通配格式的域名（如 *.example.com）：保持通配语义，补全为 ||*.域名^ 供 AdGuard 识别
    if "*" in line:
        d = line.lstrip("*.").rstrip(".")
        if d and DOMAIN_RE.match(d):
            return f"||*.{d}^"
        return None
    # 纯域名
    return domain_rule(line)

def dedupe_key(rule):
    """去重键：全部规则已统一小写，直接大小写不敏感去重"""
    return rule.lower()

def write_output(path, rules, part=None, total_parts=None, total_rules=None):
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
    header = ["! Title: Merged AdGuard Home Filter (block rules only)"]
    if part is not None:
        header[0] += f" [Part {part}/{total_parts}]"
    header += [
        f"! Updated: {now} UTC",
        f"! Rules: {len(rules)}" + (f" (total {total_rules})" if total_rules else ""),
        "! Expires: 1 day",
        "! Homepage: auto-generated by GitHub Actions",
        "",
    ]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(header + rules) + "\n")
    size_mb = os.path.getsize(path) / 1024 / 1024
    print(f"  写入 {path}: {len(rules)} 条, {size_mb:.1f} MB")

def main():
    # 清理上一次运行遗留的输出文件，避免残留过期分片
    for old in glob.glob("adguard-filter*.txt"):
        os.remove(old)

    with open(SOURCES_FILE, encoding="utf-8") as f:
        urls = [l.strip() for l in f if l.strip() and not l.startswith("#")]
    print(f"共 {len(urls)} 个规则源")

    rules, seen = [], set()
    failed = 0
    texts = fetch_all(urls)
    for url in urls:
        print(f"处理: {url}")
        text = texts[url]
        if text is None:
            failed += 1
            print(f"  [skip] 源不可用，跳过: {url}", file=sys.stderr)
            continue
        kept = 0
        for line in text.splitlines():
            r = normalize(line)
            if r is None:
                continue
            k = dedupe_key(r)
            if k not in seen:   # 有序去重（大小写不敏感）
                seen.add(k)
                rules.append(r)
                kept += 1
        print(f"  有效规则: {kept}")

    # 保底检查：大面积源失效时结果必然残缺，宁可任务失败也不覆盖线上完好版本
    if failed * 2 > len(urls):
        print(f"[error] {failed}/{len(urls)} 个源拉取失败（过半），终止推送，保留线上现有版本",
              file=sys.stderr)
        sys.exit(1)
    if len(rules) < MIN_RULES:
        print(f"[error] 合并结果仅 {len(rules)} 条（低于 {MIN_RULES}），疑似异常，终止推送",
              file=sys.stderr)
        sys.exit(1)

    # 单文件优先：先汇总写入一个文件
    write_output(OUTPUT_SINGLE, rules)
    size_mb = os.path.getsize(OUTPUT_SINGLE) / 1024 / 1024

    if size_mb > SIZE_LIMIT_MB:
        # 应急分片：仅当超过 GitHub 100MB 硬限制的安全线才拆分
        print(f"[warn] 单文件 {size_mb:.1f} MB 超过 {SIZE_LIMIT_MB} MB 安全线，自动分片", file=sys.stderr)
        os.remove(OUTPUT_SINGLE)
        parts_count = math.ceil(size_mb / PART_TARGET_MB)
        chunk_lines = math.ceil(len(rules) / parts_count)
        parts = [rules[i:i + chunk_lines] for i in range(0, len(rules), chunk_lines)]
        for i, chunk in enumerate(parts, 1):
            write_output(OUTPUT_PART_FMT.format(i), chunk,
                         part=i, total_parts=len(parts), total_rules=len(rules))

    print(f"完成，共 {len(rules)} 条拦截规则（{len(urls) - failed}/{len(urls)} 个源成功）")
    if failed:
        print(f"注意：{failed} 个源拉取失败已跳过", file=sys.stderr)

if __name__ == "__main__":
    main()
